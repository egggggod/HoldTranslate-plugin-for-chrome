(function () {
  'use strict';

  const modules = globalThis.__HOLD_TRANSLATE_MODULES__ ||= {};

  modules.createYouTubeSubtitles = function ({ config, subtitles }) {
    const asrStates = new Map();
    const ASR_TRANSLATION_DELAY = 180;
    const ASR_MAX_BATCH_WAIT = 600;
    const ASR_MAX_RETENTION = 1500;
    const ASR_DOM_GAP_DELAY = 120;
    let events = null;
    let videoEvents = null;
    let boundVideo = null;
    let observer = null;
    let observedTarget = null;
    let heartbeat = null;
    let attachTimer = null;
    let trackRequest = null;
    let cues = [];
    let trackUrl = null;
    let trackKey = null;
    let trackVssId = null;
    let videoId = null;
    let generation = 0;
    let displayGeneration = 0;
    let unitSequence = 0;
    let seekCaptionTexts = new WeakMap();
    let navigating = false;
    let seeking = false;
    let autoGenerated = false;

    const normalize = text => (text || '').replace(/\s+/g, ' ').trim();
    const getTokens = text => normalize(text).toLowerCase().match(/[\p{L}\p{N}]+(?:['’][\p{L}\p{N}]+)*/gu) || [];
    const getVideoId = () => {
      const pageUrl = new URL(window.location.href);
      return pageUrl.searchParams.get('v') || (pageUrl.pathname.match(/^\/(?:shorts|embed|live)\/([^/?]+)/) || [])[1] || '';
    };

    function findSequence(tokens, sequence) {
      if (!sequence.length || sequence.length > tokens.length) return -1;
      return tokens.findIndex((token, index) => token === sequence[0] &&
        sequence.every((part, offset) => tokens[index + offset] === part));
    }

    function extractText(element) {
      const clone = element.cloneNode(true);
      clone.querySelectorAll('br').forEach(lineBreak => lineBreak.replaceWith(' '));
      return normalize(clone.textContent);
    }

    function windowText(captionWindow) {
      return normalize(Array.from(captionWindow.querySelectorAll('.ytp-caption-segment')).map(extractText).join(' '));
    }

    function isVisible(captionWindow) {
      if (!captionWindow.isConnected || captionWindow.classList.contains('ytp-caption-window-hide')) return false;
      for (let element = captionWindow; element; element = element.parentElement) {
        if (element.hidden || element.getAttribute('aria-hidden') === 'true') return false;
        const style = window.getComputedStyle(element);
        if (style.display === 'none' || style.visibility === 'hidden') return false;
        if (element.id === 'movie_player') break;
      }
      return true;
    }

    function clearSubtitle(subtitle) {
      if (!subtitle) return;
      subtitle.textContent = '';
      Object.assign(subtitle.dataset, {
        empty: 'true', originalText: '', translatedText: '', displayKey: '', requestKey: ''
      });
      subtitle.style.setProperty('display', 'none', 'important');
    }

    function formatTranslation(text, segments, captionWindow) {
      const clean = normalize(text);
      if (!clean || clean.length <= 18 || !segments.length) return clean;
      const style = window.getComputedStyle(segments[0]);
      const lineHeight = parseFloat(style.lineHeight) || parseFloat(style.fontSize) * 1.35 || 24;
      const captionText = captionWindow.querySelector('.captions-text');
      const multiline = captionWindow.querySelector('br') ||
        (captionText && captionText.clientHeight > lineHeight * 1.45) ||
        (segments.length > 1 && Math.abs(segments[1].offsetTop - segments[0].offsetTop) > 8);
      if (!multiline) return clean;
      const midpoint = clean.length / 2;
      let split = Math.round(midpoint);
      let distance = Infinity;
      for (const match of clean.matchAll(/[，、；： ,;]/g)) {
        if (match.index < clean.length * 0.28 || match.index > clean.length * 0.72) continue;
        if (Math.abs(match.index - midpoint) < distance) {
          split = match.index + 1;
          distance = Math.abs(match.index - midpoint);
        }
      }
      return clean.slice(0, split).trim() + '\n' + clean.slice(split).trim();
    }

    function applyDisplay(captionWindow, segments, subtitle) {
      const monolingual = config.subtitleMode === 'monolingual';
      segments.forEach(segment => segment.style.setProperty('display', monolingual ? 'none' : 'inline-block', 'important'));
      const captionText = captionWindow.querySelector('.captions-text');
      if (captionText) captionText.style.setProperty('display', monolingual ? 'none' : 'block', 'important');
      if (!subtitle) return;
      subtitle.style.setProperty('display', subtitle.dataset.empty === 'true' ? 'none' : 'block', 'important');
      subtitle.style.setProperty('color', config.textColor, 'important');
      if (segments.length) {
        const style = window.getComputedStyle(segments[0]);
        for (const property of ['font-family', 'font-size', 'font-weight', 'letter-spacing', 'font-style']) {
          if (style.getPropertyValue(property)) subtitle.style.setProperty(property, style.getPropertyValue(property), 'important');
        }
        subtitle.style.setProperty('line-height', style.lineHeight === 'normal' ? '1.35' : style.lineHeight, 'important');
      }
    }

    function showTranslation(subtitle, text, translation, segments, captionWindow) {
      const formatted = formatTranslation(translation, segments, captionWindow);
      if (subtitle.textContent !== formatted) subtitle.textContent = formatted;
      subtitle.dataset.originalText = text;
      subtitle.dataset.translatedText = translation;
      subtitle.dataset.empty = 'false';
    }

    function getActiveCue(time, text, asr = false) {
      let match = null;
      let score = 0;
      const nativeTokens = asr ? getTokens(text) : null;
      cues.forEach(cue => {
        if (time < cue.start || time >= cue.end) return;
        if (!asr) {
          if (cue.text === text && (!match || cue.start > match.start)) match = cue;
          return;
        }
        const spokenText = cue.segments && cue.segments.length ?
          cue.segments.filter(segment => segment.start <= time).map(segment => segment.text).join('') : cue.text;
        const spokenTokens = getTokens(spokenText);
        const overlap = Math.min(nativeTokens.length, spokenTokens.length);
        if (!overlap || (overlap < 2 && nativeTokens.length !== 1)) return;
        if (findSequence(nativeTokens, spokenTokens) < 0 && findSequence(spokenTokens, nativeTokens) < 0) return;
        if (!match || overlap > score || (overlap === score && cue.start > match.start)) {
          match = cue;
          score = overlap;
        }
      });
      return match;
    }

    function disposeState(state) {
      if (!state || asrStates.get(state.key) !== state) return;
      clearTimeout(state.translationTimer);
      clearTimeout(state.retentionTimer);
      clearTimeout(state.gapTimer);
      asrStates.delete(state.key);
      clearSubtitle(state.subtitle);
    }

    function disposeWindow(captionWindow) {
      Array.from(asrStates.values()).filter(state => state.window === captionWindow).forEach(disposeState);
    }

    function resetSession(nextVideoId = getVideoId()) {
      Array.from(asrStates.values()).forEach(disposeState);
      if (trackRequest) trackRequest.abort();
      trackRequest = null;
      if (subtitles.clearPending) subtitles.clearPending();
      generation++;
      displayGeneration++;
      videoId = nextVideoId;
      trackUrl = null;
      trackKey = null;
      trackVssId = null;
      autoGenerated = false;
      cues = [];
      seekCaptionTexts = new WeakMap();
      seeking = false;
      document.querySelectorAll('.holdtranslate-yt-sub').forEach(subtitle => subtitle.remove());
    }

    function isStateActive(state) {
      const video = document.querySelector('video');
      return events && asrStates.get(state.key) === state && config.videoSubtitlesEnabled && !navigating &&
        state.generation === generation && state.displayGeneration === displayGeneration &&
        !seeking && !(video && video.seeking);
    }

    function isCurrent(state) {
      return isStateActive(state) && isVisible(state.window);
    }

    function getTextChange(previousText, currentText) {
      if (previousText === currentText) return 'same';
      const previous = getTokens(previousText);
      const current = getTokens(currentText);
      if (!previous.length || !current.length) return 'new';
      if (findSequence(current, previous) === 0 && current.length >= previous.length) {
        return /[.!?。？！]\s*$/.test(previousText) && current.length > previous.length ? 'new' : 'append';
      }
      let commonPrefix = 0;
      while (commonPrefix < Math.min(previous.length, current.length) && previous[commonPrefix] === current[commonPrefix]) {
        commonPrefix++;
      }
      if (commonPrefix >= 2 && commonPrefix >= Math.min(previous.length, current.length) / 2) return 'correction';
      for (let overlap = Math.min(previous.length, current.length); overlap >= 2; overlap--) {
        if (previous.slice(-overlap).every((token, index) => token === current[index])) return 'roll';
      }
      return 'new';
    }

    function acceptTranslation(state, snapshot, translation) {
      if (!translation || !isStateActive(state) || (!isVisible(state.window) && state.window.isConnected && !state.gapSince)) return false;
      const currentTokens = getTokens(state.text);
      const snapshotTokens = getTokens(snapshot.text);
      const position = findSequence(currentTokens, snapshotTokens);
      if (position < 0 || (state.expiredText === snapshot.text && snapshot.text !== state.text)) return false;
      const video = document.querySelector('video');
      const mediaLag = state.mediaTime - snapshot.mediaTime;
      if (snapshot.text !== state.text && mediaLag > ASR_MAX_RETENTION * Math.max(1, video ? video.playbackRate : 1)) return false;
      if (state.displayed) {
        if (state.displayed.text === snapshot.text && state.displayed.translation === translation) return false;
        const displayedTokens = getTokens(state.displayed.text);
        const displayedPosition = findSequence(currentTokens, displayedTokens);
        const progress = position + snapshotTokens.length;
        const displayedProgress = displayedPosition + displayedTokens.length;
        if (displayedPosition >= 0 && (progress < displayedProgress ||
            (progress === displayedProgress && snapshot.revision < state.displayed.revision))) return false;
      }
      state.displayed = { ...snapshot, translation };
      state.retainUntil = snapshot.text === state.text ? 0 : Date.now() + ASR_MAX_RETENTION;
      return true;
    }

    function scheduleTranslation(state) {
      if (!isCurrent(state) || state.inFlight || subtitles.getCached(state.text)) return;
      if (state.requestedRevision === state.revision && !state.retryAfter) return;
      const now = Date.now();
      if (!state.pendingSince) state.pendingSince = now;
      const due = Math.max(state.retryAfter || 0,
        Math.min(state.changedAt + ASR_TRANSLATION_DELAY, state.pendingSince + ASR_MAX_BATCH_WAIT));
      clearTimeout(state.translationTimer);
      state.translationTimer = setTimeout(() => {
        state.translationTimer = null;
        if (!isCurrent(state) || state.inFlight) return;
        const snapshot = { text: state.text, revision: state.revision, mediaTime: state.mediaTime };
        state.inFlight = snapshot;
        state.requestedRevision = snapshot.revision;
        state.pendingSince = 0;
        state.retryAfter = 0;
        subtitles.translate(snapshot.text, translation => {
          if (acceptTranslation(state, snapshot, translation)) render();
        }, success => {
          if (state.inFlight !== snapshot) return;
          state.inFlight = null;
          if (!success) state.retryAfter = Date.now() + 500;
          if (isCurrent(state) && (state.text !== snapshot.text || !success)) scheduleTranslation(state);
        });
      }, Math.max(0, due - now));
    }

    function holdDomGap(captionWindow) {
      const state = Array.from(asrStates.values()).find(candidate => candidate.window === captionWindow);
      if (!state || !isCurrent(state)) return false;
      if (!state.gapSince) {
        state.gapSince = Date.now();
        state.gapTimer = setTimeout(() => {
          disposeState(state);
          if (observer) observer.takeRecords();
        }, ASR_DOM_GAP_DELAY);
      }
      return Date.now() - state.gapSince < ASR_DOM_GAP_DELAY;
    }

    function renderAsr(captionWindow, subtitle, segments, text, time, windowIndex, cue) {
      const timelineKey = cue ? JSON.stringify([cue.windowId, cue.unitStart === undefined ? cue.start : cue.unitStart]) : null;
      const key = cue && cue.windowId !== undefined ? 'timed:' + cue.windowId : captionWindow.id || 'window:' + windowIndex;
      let state = asrStates.get(key);
      if (!state) {
        state = Array.from(asrStates.values()).find(candidate =>
          (candidate.window === captionWindow || !candidate.window.isConnected) &&
          (candidate.timelineKey === timelineKey || !candidate.timelineKey || !timelineKey) &&
          getTextChange(candidate.text, text) !== 'new');
        if (state) {
          asrStates.delete(state.key);
          state.key = key;
          asrStates.set(key, state);
        }
      }
      const change = state ? getTextChange(state.text, text) : 'new';
      const sameTimeline = state && timelineKey && state.timelineKey === timelineKey;
      const rollingContinuation = state && cue && cue.windowId === state.windowId &&
        (change === 'append' || change === 'roll') && !/[.!?。？！]\s*$/.test(state.text) &&
        time - state.changedMediaTime <= 1000;
      if (state && ((timelineKey && state.timelineKey && !sameTimeline && !rollingContinuation) ||
          (change === 'new' && !sameTimeline) ||
          (change === 'new' && /[.!?。？！]\s*$/.test(state.text)) ||
          (change !== 'same' && !sameTimeline && (time - state.changedMediaTime > 1000 || time - state.startedAt > 8000)))) {
        disposeState(state);
        state = null;
      }
      Array.from(asrStates.values()).filter(candidate => candidate !== state && candidate.window === captionWindow).forEach(disposeState);
      if (!state) {
        clearSubtitle(subtitle);
        state = {
          key, id: ++unitSequence, generation, displayGeneration,
          revision: 0, requestedRevision: -1, startedAt: time, displayed: null, text: ''
        };
        asrStates.set(key, state);
      }
      state.window = captionWindow;
      state.subtitle = subtitle;
      state.timelineKey = timelineKey || state.timelineKey;
      if (cue) state.windowId = cue.windowId;
      state.mediaTime = time;
      clearTimeout(state.gapTimer);
      state.gapSince = 0;
      if (state.text !== text) {
        state.text = text;
        state.revision++;
        state.changedAt = Date.now();
        state.changedMediaTime = time;
        if (state.displayed) {
          const stillVisible = findSequence(getTokens(text), getTokens(state.displayed.text)) >= 0;
          if (!stillVisible && change !== 'roll') {
            state.displayed = null;
            clearSubtitle(subtitle);
          } else if (!state.retainUntil) {
            state.retainUntil = Date.now() + (change === 'roll' ? ASR_MAX_BATCH_WAIT : ASR_MAX_RETENTION);
          }
        }
      }
      const cached = subtitles.getCached(text);
      if (cached) acceptTranslation(state, { text, revision: state.revision, mediaTime: time }, cached);
      clearTimeout(state.retentionTimer);
      if (state.displayed && state.displayed.text !== text && state.retainUntil) {
        if (Date.now() >= state.retainUntil) {
          state.expiredText = state.displayed.text;
          state.displayed = null;
          clearSubtitle(subtitle);
        } else {
          state.retentionTimer = setTimeout(() => {
            if (isCurrent(state)) render();
          }, state.retainUntil - Date.now());
        }
      } else {
        state.retainUntil = 0;
      }
      subtitle.dataset.asr = 'true';
      subtitle.dataset.displayKey = `${generation}:${displayGeneration}:asr:${state.id}`;
      if (state.displayed) {
        showTranslation(subtitle, state.displayed.text, state.displayed.translation, segments, captionWindow);
      }
      applyDisplay(captionWindow, segments, subtitle);
      if (!cached) scheduleTranslation(state);
    }

    function render() {
      if (!events || !config.videoSubtitlesEnabled || navigating) return;
      const windows = Array.from(document.querySelectorAll('.caption-window'));
      asrStates.forEach(state => {
        if (!state.window.isConnected && !state.gapTimer) {
          state.gapTimer = setTimeout(() => disposeState(state), ASR_DOM_GAP_DELAY);
        }
      });
      const video = document.querySelector('video');
      const time = video ? Math.round(video.currentTime * 1000) : 0;
      windows.forEach((captionWindow, windowIndex) => {
        const asr = autoGenerated || captionWindow.classList.contains('ytp-caption-window-rollup');
        let subtitle = captionWindow.querySelector('.holdtranslate-yt-sub');
        if (!isVisible(captionWindow)) {
          disposeWindow(captionWindow);
          clearSubtitle(subtitle);
          seekCaptionTexts.delete(captionWindow);
          return;
        }
        const segments = captionWindow.querySelectorAll('.ytp-caption-segment');
        const text = windowText(captionWindow);
        if (!text) {
          if (asr && holdDomGap(captionWindow)) return;
          disposeWindow(captionWindow);
          clearSubtitle(subtitle);
          return;
        }
        const cue = getActiveCue(time, text, asr);
        if (seeking || (video && video.seeking) || (seekCaptionTexts.get(captionWindow) === text && !cue)) {
          disposeWindow(captionWindow);
          clearSubtitle(subtitle);
          return;
        }
        seekCaptionTexts.delete(captionWindow);
        if (!subtitle) {
          subtitle = document.createElement('div');
          subtitle.className = 'holdtranslate-yt-sub';
          clearSubtitle(subtitle);
          captionWindow.appendChild(subtitle);
        }
        if (asr) {
          renderAsr(captionWindow, subtitle, segments, text, time, windowIndex, cue);
          return;
        }
        const cueKey = cue ? `${cue.start}:${cue.end}` : '';
        const displayKey = `${generation}:${displayGeneration}:${cueKey}:${text}`;
        if (subtitle.dataset.displayKey !== displayKey) clearSubtitle(subtitle);
        subtitle.dataset.displayKey = displayKey;
        const cached = subtitles.getCached(text);
        if (cached) showTranslation(subtitle, text, cached, segments, captionWindow);
        applyDisplay(captionWindow, segments, subtitle);
        if (cached || (subtitle.dataset.requestKey === displayKey && subtitles.isPending(text))) return;
        subtitle.dataset.requestKey = displayKey;
        subtitles.translate(text, () => {
          if (events && !navigating && subtitle.isConnected && subtitle.dataset.displayKey === displayKey) render();
        });
      });
      if (observer) observer.takeRecords();
    }

    function parseTimedText(rawText) {
      if (!rawText || typeof rawText !== 'string') return [];
      const trimmed = rawText.trim();
      try {
        if (trimmed.startsWith('{')) {
          const data = JSON.parse(trimmed);
          if (!Array.isArray(data.events)) return [];
          const parsed = [];
          const windows = new Map();
          data.events.forEach((event, index) => {
            if (!event.segs || !event.segs.length) return;
            const start = Number(event.tStartMs || 0);
            let duration = Number(event.dDurationMs);
            if (!(duration > 0)) {
              const next = data.events.slice(index + 1).find(candidate => Number(candidate.tStartMs) > start);
              duration = next ? Number(next.tStartMs) - start : 3000;
            }
            if (!Number.isFinite(start) || !Number.isFinite(duration) || start < 0) return;
            const windowId = event.wWinId === undefined ? 0 : event.wWinId;
            const previous = windows.get(windowId);
            const append = Boolean(event.aAppend && previous && start <= previous.end + 900);
            const segments = event.segs.map(segment => ({
              start: start + (Number(segment.tOffsetMs) || 0), text: segment.utf8 || ''
            }));
            const raw = (append ? previous.raw : '') + segments.map(segment => segment.text).join('');
            const text = normalize(raw);
            if (!text) return;
            const isAsr = append || event.segs.some(segment => Number(segment.tOffsetMs) > 0 || segment.acAsrConf !== undefined);
            const cue = {
              start, end: append ? Math.max(previous.end, start + duration) : start + duration,
              text, raw, windowId, isAsr, unitStart: append ? previous.unitStart : start,
              segments: append ? [...previous.segments, ...segments] : segments
            };
            if (previous && (isAsr || previous.isAsr) && start > previous.start) {
              previous.end = Math.min(previous.end, start);
            }
            parsed.push(cue);
            windows.set(windowId, cue);
          });
          return parsed.filter(cue => cue.end > cue.start).sort((first, second) => first.start - second.start);
        }
        if (trimmed.startsWith('<')) {
          return Array.from(new DOMParser().parseFromString(trimmed, 'text/xml').querySelectorAll('text'), node => ({
            start: Math.round(parseFloat(node.getAttribute('start') || '0') * 1000),
            end: Math.round((parseFloat(node.getAttribute('start') || '0') + parseFloat(node.getAttribute('dur') || '3')) * 1000),
            text: normalize(node.textContent)
          })).filter(cue => cue.text && Number.isFinite(cue.start) && Number.isFinite(cue.end) && cue.end > cue.start)
            .sort((first, second) => first.start - second.start);
        }
      } catch (error) {}
      return [];
    }

    function getTrackKey(url) {
      return JSON.stringify(['v', 'lang', 'kind', 'name'].map(name => url.searchParams.get(name) || ''));
    }

    function getTrackName(track) {
      if (!track || !track.name) return '';
      if (typeof track.name === 'string') return track.name;
      if (typeof track.name.simpleText === 'string') return track.name.simpleText;
      if (Array.isArray(track.name.runs)) return track.name.runs.map(run => run.text || '').join('');
      return '';
    }

    function mergeCues(incoming) {
      if (incoming.some(cue => cue.isAsr)) autoGenerated = true;
      const unique = new Map([...cues, ...incoming].map(cue => [JSON.stringify([cue.windowId, cue.start, cue.text]), cue]));
      cues = Array.from(unique.values()).sort((first, second) => first.start - second.start);
      render();
      prefetch();
    }

    function isSessionCurrent(session, expectedVideo, expectedTrack) {
      return events && config.videoSubtitlesEnabled && !navigating && session === generation &&
        expectedVideo === getVideoId() && expectedVideo === videoId && expectedTrack === trackKey;
    }

    function loadTrack(rawUrl, expectedVideo) {
      let url;
      try {
        url = new URL(rawUrl, window.location.href);
      } catch (error) {
        return;
      }
      const key = getTrackKey(url);
      if (!events || navigating || !expectedVideo || expectedVideo !== getVideoId()) return;
      if (videoId !== expectedVideo || trackKey !== key) resetSession(expectedVideo);
      trackKey = key;
      if (url.searchParams.get('kind') === 'asr') autoGenerated = true;
      if (trackUrl) return;
      trackUrl = rawUrl;
      const session = generation;
      const request = new AbortController();
      trackRequest = request;
      url.searchParams.set('fmt', 'json3');
      url.searchParams.delete('tlang');
      fetch(url.href, { signal: request.signal }).then(response => response.ok ? response.text() : null).then(raw => {
        if (!isSessionCurrent(session, expectedVideo, key)) return;
        const parsed = parseTimedText(raw);
        if (parsed.length) mergeCues(parsed);
        else trackUrl = null;
      }).catch(() => {
        if (isSessionCurrent(session, expectedVideo, key)) trackUrl = null;
      }).finally(() => {
        if (trackRequest === request) trackRequest = null;
      });
    }

    function interceptTrack(payload) {
      let url;
      try {
        url = new URL(payload.url, window.location.href);
      } catch (error) {
        return;
      }
      const currentVideo = getVideoId();
      if (url.searchParams.has('tlang') || !payload.text || !currentVideo ||
          (url.searchParams.get('v') || payload.videoId) !== currentVideo ||
          (payload.videoId && payload.videoId !== currentVideo)) return;
      const key = getTrackKey(url);
      if (videoId !== currentVideo) resetSession(currentVideo);
      if (trackKey && trackKey !== key) return;
      const parsed = parseTimedText(payload.text);
      if (!parsed.length) return;
      loadTrack(payload.url, currentVideo);
      mergeCues(parsed);
    }

    function detectTracks({ tracks, activeTrack, videoId: detectedVideo }) {
      if (!Array.isArray(tracks) || !tracks.length) return;
      const currentVideo = getVideoId();
      if (!currentVideo || (detectedVideo && detectedVideo !== currentVideo)) return;
      const activeName = getTrackName(activeTrack);
      const selected = activeTrack && tracks.find(track => activeTrack.vssId ?
        track.vssId === activeTrack.vssId :
        track.languageCode === activeTrack.languageCode &&
        (track.kind || '') === (activeTrack.kind || '') &&
        (!activeName || getTrackName(track) === activeName));
      const track = activeTrack && (activeTrack.vssId || activeTrack.languageCode) ? selected || activeTrack :
        tracks.find(candidate => candidate.languageCode === config.sourceLang) || tracks[0];
      if (!track) return;
      const isTrackAsr = track.kind === 'asr' || Boolean(track.vssId && track.vssId.startsWith('a.'));
      if (!track.baseUrl) {
        const nextKind = track.kind || (isTrackAsr ? 'asr' : '');
        const nextName = getTrackName(track);
        if (trackKey && track.languageCode) {
          const previous = JSON.parse(trackKey);
          const previousVssId = trackVssId || (previous[2] === 'asr' ? 'a.' : '.') + previous[1] + (previous[3] ? '.' + previous[3] : '');
          const changed = track.vssId ? track.vssId !== previousVssId :
            previous[1] !== track.languageCode || previous[2] !== nextKind || previous[3] !== nextName;
          if (changed) resetSession(currentVideo);
        } else if (trackVssId && track.vssId && trackVssId !== track.vssId) {
          resetSession(currentVideo);
        }
        trackVssId = track.vssId || trackVssId;
        if (isTrackAsr) autoGenerated = true;
        return;
      }
      let url;
      try {
        url = new URL(track.baseUrl, window.location.href);
      } catch (error) {
        return;
      }
      if ((url.searchParams.get('v') || detectedVideo) !== currentVideo) return;
      loadTrack(track.baseUrl, currentVideo);
      trackVssId = track.vssId || null;
      if (isTrackAsr) autoGenerated = true;
    }

    function requestTracks() {
      if (events && !navigating) window.postMessage({ source: 'holdtranslate-content', type: 'REQUEST_TRACKS' }, '*');
    }

    function prefetch() {
      const video = document.querySelector('video');
      if (!events || navigating || seeking || autoGenerated || !video || video.seeking) return;
      const time = Math.round(video.currentTime * 1000);
      const session = generation;
      cues.filter(cue => cue.end > time && cue.start <= time + 45000 &&
        !subtitles.getCached(cue.text) && !subtitles.isPending(cue.text)).slice(0, 4).forEach(cue => {
        subtitles.translate(cue.text, () => {
          if (session === generation) render();
        });
      });
    }

    function bindVideo() {
      const video = document.querySelector('video');
      if (video === boundVideo) return;
      if (videoEvents) videoEvents.abort();
      boundVideo = video;
      seeking = Boolean(video && video.seeking);
      videoEvents = video ? new AbortController() : null;
      if (!video) return;
      const options = { passive: true, signal: videoEvents.signal };
      video.addEventListener('seeking', () => {
        seeking = true;
        displayGeneration++;
        Array.from(asrStates.values()).forEach(disposeState);
        seekCaptionTexts = new WeakMap();
        document.querySelectorAll('.caption-window').forEach(captionWindow => seekCaptionTexts.set(captionWindow, windowText(captionWindow)));
        render();
      }, options);
      const resume = () => {
        seeking = false;
        render();
        prefetch();
      };
      video.addEventListener('seeked', resume, options);
      video.addEventListener('play', resume, options);
      let lastUpdate = 0;
      video.addEventListener('timeupdate', () => {
        if (Date.now() - lastUpdate > 250) {
          lastUpdate = Date.now();
          if (!seeking) render();
        }
      }, options);
      video.addEventListener('ratechange', render, options);
      video.addEventListener('pause', render, options);
      video.addEventListener('emptied', () => resetSession(), options);
    }

    function attachObserver() {
      if (!events) return;
      bindVideo();
      const target = document.querySelector('#movie_player, .html5-video-player') || document.querySelector('#player') || document.body;
      if (target !== observedTarget) {
        if (observer) observer.disconnect();
        observedTarget = target;
        observer = target ? new MutationObserver(mutations => {
          if (!events || navigating) return;
          const external = mutations.some(mutation => {
            const element = mutation.target.nodeType === 1 ? mutation.target : mutation.target.parentElement;
            if (!element || element.closest('.holdtranslate-yt-sub')) return false;
            if (mutation.type === 'attributes' && !element.closest('.caption-window') && !element.querySelector('.caption-window')) return false;
            if (mutation.type !== 'attributes') {
              const captionWindow = element.closest('.caption-window');
              if (captionWindow) seekCaptionTexts.delete(captionWindow);
            }
            return true;
          });
          if (external) render();
        }) : null;
        if (observer) observer.observe(target, {
          childList: true, subtree: true, characterData: true,
          attributes: true, attributeFilter: ['class', 'style', 'hidden', 'aria-hidden']
        });
      }
      render();
    }

    function scheduleAttach(delay) {
      clearTimeout(attachTimer);
      attachTimer = setTimeout(attachObserver, delay);
    }

    function start() {
      if (!window.location.hostname.includes('youtube.com') || !config.videoSubtitlesEnabled) return;
      if (events) {
        render();
        return;
      }
      events = new AbortController();
      navigating = false;
      const options = { passive: true, signal: events.signal };
      window.addEventListener('message', event => {
        if (event.source !== window || navigating || !event.data || event.data.source !== 'holdtranslate-bridge') return;
        const { type, payload } = event.data;
        if (!payload) return;
        if (type === 'TIMED_TEXT_INTERCEPTED') interceptTrack(payload);
        else if (type === 'CAPTION_TRACKS_DETECTED') detectTracks(payload);
      }, options);
      window.addEventListener('yt-navigate-start', () => {
        navigating = true;
        resetSession();
      }, options);
      window.addEventListener('yt-navigate-finish', () => {
        navigating = false;
        resetSession();
        requestTracks();
        scheduleAttach(500);
      }, options);
      window.addEventListener('fullscreenchange', () => scheduleAttach(300), options);
      attachObserver();
      requestTracks();
      heartbeat = setInterval(() => {
        attachObserver();
        if (!trackUrl) requestTracks();
        const video = document.querySelector('video');
        if (video && !video.paused) prefetch();
      }, 2000);
    }

    function stop() {
      if (!events) return;
      events.abort();
      events = null;
      if (videoEvents) videoEvents.abort();
      videoEvents = null;
      boundVideo = null;
      if (observer) observer.disconnect();
      observer = null;
      observedTarget = null;
      clearInterval(heartbeat);
      clearTimeout(attachTimer);
      heartbeat = null;
      attachTimer = null;
      resetSession();
      document.querySelectorAll('.caption-window .ytp-caption-segment, .caption-window .captions-text')
        .forEach(element => element.style.removeProperty('display'));
    }

    return { start, stop, refresh: render };
  };
})();
